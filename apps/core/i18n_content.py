_CHAR_MAP = str.maketrans({
    'ї': 'и',
    'Ї': 'И',
    'є': 'е',
    'Є': 'Е',
    'ґ': 'г',
    'Ґ': 'Г',
    'і': 'и',
    'І': 'И',
    'щ': 'щ',
    'Щ': 'Щ',
})


def is_ru_language() -> bool:
    return translation.get_language() == 'ru'


def localized_text(ua_value: str | None, ru_value: str | None) -> str:
    ua = (ua_value or '').strip()
    ru = (ru_value or '').strip()
    if is_ru_language() and ru:
        return ru
    return ua


def translate_ua_to_ru(text: str) -> str:
    """Rule-based UA→RU for seeding *_ru fields without external APIs."""
    if not text or not text.strip():
        return ''

    result = text
    for ua, ru in _UA_RU_PHRASES:
        result = result.replace(ua, ru)

    # Suffix-style replacements common in UA marketing copy.
    suffix_rules = (
        (r'ність\b', 'ность'),
        (r'ністью\b', 'ностью'),
        (r'цію\b', 'цию'),
        (r'ції\b', 'ции'),
        (r'цій\b', 'ций'),
        (r'ування\b', 'ование'),
        (r'уванням\b', 'ованием'),
        (r'уванням\b', 'ованием'),
        (r'уват\b', 'овать'),
        (r'ються\b', 'ются'),
        (r'ється\b', 'ется'),
        (r'ються', 'ются'),
        (r'ється', 'ется'),
        (r'ього\b', 'ого'),
        (r'ній\b', 'ной'),
        (r'ній', 'ной'),
        (r'ній\b', 'ной'),
        (r'ній', 'ной'),
        (r'ько\b', 'ько'),
    )
    for pattern, replacement in suffix_rules:
        result = re.sub(pattern, replacement, result)

    return result.translate(_CHAR_MAP)
